// Embeds the GeoJSON fixtures of test/examples/<module> into a Dart file,
// test/fixtures/<module>_fixtures.g.dart, so the fixture suites also run in
// the browser (`dart test -p chrome`), where `dart:io` is not available.
//
// Usage:
//   dart run tool/embed_fixtures.dart <module> ...  embeds these modules
//   dart run tool/embed_fixtures.dart               regenerates all
//                                                   existing fixture files
//
// The output is already `dart format`-clean, so
// test/components/embedded_fixtures_test.dart can compare it byte for byte.
import 'dart:io';

const fixturesDir = 'test/fixtures';
const _suffix = '_fixtures.g.dart';

void main(List<String> args) {
  final modules = args.isEmpty ? embeddedModules() : args;
  for (final module in modules) {
    final file = File(outputPath(module));
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(generate(module));
    stdout.writeln('wrote ${file.path}');
  }
}

/// The modules that have an embedded fixture file.
List<String> embeddedModules() {
  final dir = Directory(fixturesDir);
  if (!dir.existsSync()) return [];
  return dir
      .listSync()
      .whereType<File>()
      .map((f) => f.uri.pathSegments.last)
      .where((name) => name.endsWith(_suffix))
      .map((name) => name.substring(0, name.length - _suffix.length))
      .toList()
    ..sort();
}

String outputPath(String module) => '$fixturesDir/$module$_suffix';

String variableName(String module) {
  final parts = module.split(RegExp(r'[_\-]'));
  final rest =
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
  return '${parts.first}${rest}Fixtures';
}

/// The generated Dart source for [module].
String generate(String module) {
  final root = Directory('test/examples/$module');
  final files = root
      .listSync(recursive: true)
      .whereType<File>()
      .where((f) => f.path.endsWith('.geojson'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final buf = StringBuffer()
    ..writeln('// GENERATED by tool/embed_fixtures.dart - do not edit.')
    ..writeln('// Source: test/examples/$module')
    ..writeln()
    ..writeln('/// Fixture contents keyed by path relative to '
        'test/examples/$module.')
    ..writeln('const Map<String, String> ${variableName(module)} = {');
  for (final file in files) {
    final rel = file.path
        .substring(root.path.length + 1)
        .replaceAll(Platform.pathSeparator, '/');
    final content = file.readAsStringSync();
    if (content.contains("'''")) {
      throw StateError("${file.path} contains ''' and cannot be embedded");
    }
    buf.writeln("  r'$rel': r'''$content''',");
  }
  buf.writeln('};');
  return buf.toString();
}
